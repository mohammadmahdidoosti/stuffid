FL = "اتصالات جابجایی سیالات عمومی"

_POLY = re.compile(r"پلی|pvc|upvc|پلیکا|\bpp\b|\bpe\b|پلیمر|پلاستیک|الفو|تزریقی|الکتروفیوژن|پوشفیت|پوش فیت|نیوپایپ|سایلنت|کامپوزیت|پنج لایه|سه لایه|تک لایه")
_METAL = re.compile(r"گالوانیزه|کروم|ابکاری|الومینیوم|فولاد|استیل|برنج|چدن|\bمس\b|مسی|فلزی|رده|دنده ای|جوشی فولاد")
_GRAVITY = re.compile(r"فاضلاب|پوشفیت|پوش فیت|سایلنت|اب باران|ناودان|کفشور|دریچه بازدید|ونت")
_PRESSURE = re.compile(r"\d+(?:[./]\d+)?\s*بار\b|\bpn\s*\d|\bsdr|فشار")


def _metal(n):
    if _POLY.search(n):
        return False
    return bool(_METAL.search(n))


_PRESSURE_SYS = re.compile(r"cpvc|c-pvc|ترموپلاستیک|پیمتاش|ویسپار|سیپکس")


def _gravity(n):
    if _GRAVITY.search(n):
        return True
    if _PRESSURE_SYS.search(n):
        return False
    if re.search(r"پلیکا|upvc|pvc", n) and not _PRESSURE.search(n):
        return True
    return False


def fitting(item, has_gravity_metal=True, has_gravity_poly=True, metal_split=True):
    """Build a function that picks the right pipe-fitting description."""
    def f(n):
        g = _gravity(n)
        m = _metal(n)
        if g and m and not has_gravity_metal:
            g = False
        if g and not m and not has_gravity_poly:
            g = False
        press = "غیر تحت فشار" if g else "تحت فشار"
        if not metal_split:
            return f"{item} انتقال مایع {press} {FL}"
        mat = "فلزی" if m else "غیر فلزی"
        return f"{item} انتقال مایع {press} {mat} {FL}"
    f.spec = {"fn": "fitting", "item": item, "gm": has_gravity_metal, "gp": has_gravity_poly, "split": metal_split}
    return f


def pipe(n):
    g = _gravity(n)
    m = _metal(n)
    return f"لوله انتقال مایع {'غیر تحت فشار' if g else 'تحت فشار'} {'فلزی' if m else 'غیر فلزی'} جابجایی سیالات عمومی"


def flange(n):
    return f"فلنج {'غیر تحت فشار' if _gravity(n) else 'تحت فشار'} {FL}"


def cap(n):
    return f"کلاهک خط لوله مایع {'غیر تحت فشار' if _gravity(n) else 'تحت فشار'} {FL}"


def nut(n):
    return ("مهره ماسوره انتقال مایع تحت فشار فلزی " if _metal(n) else
            "مهره ماسوره انتقال مایع تحت فشار غیرفلزی ") + FL


pipe.spec = {"fn": "pipe"}
flange.spec = {"fn": "flange"}
